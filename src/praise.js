  /* ---------- 确定性洗牌（LCG 种子） ---------- */
  function seededShuffle(arr, seed) {
    var a = arr.slice(), s = seed >>> 0 || 1;
    function rnd() { s = (s * 1664525 + 1013904223) >>> 0; return s / 4294967296; }
    for (var i = a.length - 1; i > 0; i--) {
      var j = Math.floor(rnd() * (i + 1));
      var t = a[i]; a[i] = a[j]; a[j] = t;
    }
    return a;
  }

